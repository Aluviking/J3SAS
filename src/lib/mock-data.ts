// Búsqueda liviana de productos para el chat de Celeste (RAG local, sin backend):
// dado el mensaje del cliente, encuentra los productos del catálogo más
// relevantes para dárselos como contexto real a la IA (así no inventa nombres,
// precios ni links).
function normalizeText(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
}

// Además de la palabra clínica ("hombre"), se incluyen formas naturales con
// las que alguien describe al destinatario del regalo/compra ("mi esposo",
// "mi hijo") — así el chat entiende de quién se habla sin que digan
// literalmente "para hombre" o "para niño".
const AUDIENCE_KEYWORDS: Record<Audience, string[]> = {
  hombre: ["hombre", "hombres", "masculino", "caballero", "esposo", "novio", "papa", "adultos", "adulto"],
  mujer: ["mujer", "mujeres", "dama", "damas", "femenino", "chica", "ella", "esposa", "novia", "mama", "adultos", "adulto"],
  nino: ["nino", "ninos", "varoncito", "hijo", "sobrino", "nieto"],
  nina: ["nina", "ninas", "hija", "sobrina", "nieta"],
};

// Palabras vacías del español conversacional: sin filtrarlas, el largo
// mínimo de 3 letras las dejaba pasar y podían "matchear" por pura
// coincidencia de substring dentro de un término real del catálogo — el caso
// que se detectó fue "que" (dentro de un mensaje tan común como "¿y qué más
// tienes?") apareciendo literalmente dentro de "chaquetas", así que CUALQUIER
// mensaje con esa palabra le daba puntaje a todas las chaquetas sin que
// tuvieran nada que ver, desplazando el producto real del que se hablaba.
const CHAT_STOPWORDS = new Set([
  "que", "hay", "mas", "para", "con", "los", "las", "una", "uno", "unos", "unas",
  "por", "esta", "este", "esa", "ese", "eso", "esto", "del", "muy", "ahi", "alli",
  "aqui", "tiene", "tienes", "tengo", "algo", "alguna", "algun", "otra", "otro",
  "otros", "otras", "cual", "cuales", "como", "donde", "cuando", "quien",
  "porque", "gusta", "gustan", "quiero", "quieres", "busco", "buscas",
  "necesito", "necesitas", "tambien", "todavia", "aun", "pero", "entonces",
  "bueno", "listo", "dime", "dame", "ver", "veo", "mira", "oye", "sobre",
  "entre", "desde", "hasta", "cada", "solo", "sola", "solos", "solas",
  "mismo", "misma", "mismos", "mismas", "hola",
]);

export function searchProductsForChat(query: string, limit = 6): Product[] {
  const words = normalizeText(query)
    .split(/[^a-z0-9]+/)
    .filter((w) => w.length >= 3 && !CHAT_STOPWORDS.has(w));
  if (words.length === 0) return [];

  // Si el mensaje nombra un público de forma explícita y exacta (palabra
  // completa, no substring), se filtra duro por ese público — sin esto, una
  // búsqueda "para hombre" con pocos resultados de hombre se rellenaba con
  // productos de mujer/niños solo por empatar en otras palabras.
  const requestedAudiences = (Object.keys(AUDIENCE_KEYWORDS) as Audience[]).filter((aud) =>
    AUDIENCE_KEYWORDS[aud].some((kw) => words.includes(kw))
  );
  const targetAudience = requestedAudiences.length === 1 ? requestedAudiences[0] : null;

  const scored = products
    .filter((p) => !targetAudience || p.audience === targetAudience)
    .map((p) => {
      const name = normalizeText(p.name);
      const description = normalizeText(p.description);
      const category = normalizeText(p.category);
      const subcategories = normalizeText((p.subcategories ?? []).join(" "));

      let score = 0;
      for (const w of words) {
        if (category.includes(w)) score += 3;
        if (name.includes(w)) score += 2;
        if (subcategories.includes(w)) score += 1;
        if (description.includes(w)) score += 1;
      }
      if (targetAudience && p.audience === targetAudience) score += 2;
      // Empate a favor de Rescate: son últimas unidades a precio especial que
      // conviene mover primero, así que ante coincidencias iguales se muestran
      // antes que el resto del catálogo regular.
      if (score > 0 && p.category === "Rescate") score += 1;
      return { product: p, score };
    });

  const ranked = scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.product);

  // Si el filtro estricto por público no dejó nada, se repite sin filtrar
  // para no devolver una lista vacía por un público que resultó no tener
  // coincidencias puntuales.
  if (ranked.length === 0 && targetAudience) {
    return searchProductsForChatUnfiltered(words, limit);
  }

  return dedupeVariants(ranked).slice(0, limit);
}

function searchProductsForChatUnfiltered(words: string[], limit: number): Product[] {
  const scored = products.map((p) => {
    const name = normalizeText(p.name);
    const description = normalizeText(p.description);
    const category = normalizeText(p.category);
    const subcategories = normalizeText((p.subcategories ?? []).join(" "));
    let score = 0;
    for (const w of words) {
      if (category.includes(w)) score += 3;
      if (name.includes(w)) score += 2;
      if (subcategories.includes(w)) score += 1;
      if (description.includes(w)) score += 1;
    }
    if (score > 0 && p.category === "Rescate") score += 1;
    return { product: p, score };
  });
  const ranked = scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.product);
  return dedupeVariants(ranked).slice(0, limit);
}

// Mapa de todo el catálogo (público → categoría → cuántos diseños hay), para
// que Celeste siempre tenga en su prompt la forma completa del inventario,
// incluso en mensajes donde la búsqueda puntual no encuentra candidatos
// específicos. Cuenta diseños reales (agrupando colores del mismo diseño),
// no cada referencia de color por separado.
export function getInventorySummary(): string {
  const audienceLabel: Record<string, string> = {
    hombre: "Hombre",
    mujer: "Dama",
    nino: "Niño",
    nina: "Niña",
  };

  const byAudience = new Map<string, Product[]>();
  for (const p of products) {
    const key = p.audience ?? "unisex";
    if (!byAudience.has(key)) byAudience.set(key, []);
    byAudience.get(key)!.push(p);
  }

  const lines: string[] = [];
  for (const [audience, list] of byAudience) {
    const designs = dedupeVariants(list);
    const byCategory = new Map<string, number>();
    for (const p of designs) {
      byCategory.set(p.category, (byCategory.get(p.category) ?? 0) + 1);
    }
    const categoriesStr = Array.from(byCategory.entries())
      .map(([cat, count]) => `${cat} (${count})`)
      .join(", ");
    const rescateCount = designs.filter((p) => p.category === "Rescate").length;
    const label = audienceLabel[audience] ?? "Unisex";
    lines.push(
      `${label} (${designs.length}): ${categoriesStr}${rescateCount > 0 ? ` [${rescateCount} de Rescate]` : ""}`
    );
  }
  return lines.join("\n");
}

