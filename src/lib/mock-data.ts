// Variantes de color del mismo diseño (ej. una blusa que solo cambia de
// color): cada color es su propio producto, agrupado por `variantGroup`.
export function getVariantSiblings(product: Product): Product[] {
  if (!product.variantGroup) return [];
  return products.filter((p) => p.variantGroup === product.variantGroup);
}

// Para vitrinas/grillas: cuando varios productos son la misma prenda en
// distintos colores (mismo `variantGroup`), se muestra una sola card — el
// color se elige dentro de la página del producto, no repitiendo la prenda.
// La card que representa al grupo es la marcada `variantPrimary` (o, si
// ninguna lo está, la primera del grupo en el catálogo).
export function dedupeVariants(list: Product[]): Product[] {
  const primaryByGroup = new Map<string, Product>();
  for (const p of products) {
    if (!p.variantGroup) continue;
    const current = primaryByGroup.get(p.variantGroup);
    if (!current || (p.variantPrimary && !current.variantPrimary)) {
      primaryByGroup.set(p.variantGroup, p);
    }
  }

  const seenGroups = new Set<string>();
  const result: Product[] = [];
  for (const p of list) {
    if (p.variantGroup) {
      if (seenGroups.has(p.variantGroup)) continue;
      seenGroups.add(p.variantGroup);
      result.push(primaryByGroup.get(p.variantGroup) ?? p);
      continue;
    }
    result.push(p);
  }
  return result;
}

// Recomendaciones "también te puede gustar/interesar": prioriza productos de
// la misma categoría (y, si es posible, la misma audiencia) antes de
// completar con el resto del catálogo, para no recomendar prendas sin relación.
export function getRelatedProducts(
  product: Pick<Product, "id" | "category" | "audience" | "variantGroup">,
  limit = 4
): Product[] {
  // Otro color de la misma prenda no es una "recomendación" real: ese
  // cambio ya se hace desde el selector de color dentro del producto.
  const pool = dedupeVariants(products).filter(
    (p) => p.id !== product.id && (!product.variantGroup || p.variantGroup !== product.variantGroup)
  );
  const sameCategoryAndAudience = pool.filter(
    (p) => p.category === product.category && (!product.audience || p.audience === product.audience)
  );
  const sameCategory = pool.filter((p) => p.category === product.category);
  const rest = pool.filter((p) => p.category !== product.category);

  const picked: Product[] = [];
  const seen = new Set<string>();
  for (const list of [sameCategoryAndAudience, sameCategory, rest]) {
    for (const p of list) {
      if (picked.length >= limit) break;
      if (seen.has(p.id)) continue;
      seen.add(p.id);
      picked.push(p);
    }
  }
  return picked;
}
